#!/usr/bin/env python3
"""
Regenerate test/transfer-sheet-fixture.json from a real PDF.

    python3 tools/transfer_sheet.py out/RaiseRoom_Transfer-Sheet.pdf
    python3 tools/make-fixture.py

The fixture is captured rather than hand-written on purpose. A hand-written
fixture tests the parser against what the author of the parser imagined the PDF
contained; this one tests it against what the generator actually produces, so a
field renamed in one place and not the other fails a test instead of failing a
customer.

Run this whenever the field definitions or the generator change.
"""

import json
import subprocess
import sys
from pathlib import Path

from pypdf import PdfReader, PdfWriter

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

# Deliberately includes the awkward formats: a currency figure with a symbol and
# separators, a percentage with a sign, a choice in sentence case, a key-person
# row with no deputy, and a second row to prove more than one is read.
SAMPLE = {
    "sheet_version": "1.0",
    "receipt_ref": "WHOP-ABC-123",
    "s_1_1": "2", "s_1_2": "3", "s_2_1": "1", "s_8_4": "5",
    "norm_reported_profit": "$420,000",
    "norm_normalised_earnings": "610000",
    "norm_period": "FY2025",
    "conc_top1": "68%", "conc_top3": "81", "conc_top5": "88",
    "conc_top1_prior": "41", "conc_direction": "Increasing",
    "kp1_person": "A. Founder", "kp1_holds": "Every top-10 customer relationship",
    "kp2_person": "B. Engineer", "kp2_holds": "Sole write access to production",
    "assum_1": "Enterprise win rate stays at 22%",
    "assum_2": "Churn stays under 1.5% monthly",
    "assum_3": "Hiring plan lands two senior engineers by Q2",
}


def main(src: Path, out: Path) -> None:
    if not src.exists():
        raise SystemExit(f"generate the sheet first: python3 tools/transfer_sheet.py {src}")

    reader = PdfReader(str(src))
    field_names = sorted({str(n).split(".")[-1] for n in (reader.get_fields() or {})})

    writer = PdfWriter(clone_from=str(src))
    writer.set_need_appearances_writer(True)
    for page in writer.pages:
        try:
            writer.update_page_form_field_values(page, SAMPLE)
        except Exception:  # noqa: BLE001 — fields live on one page; the rest are no-ops
            pass

    tmp = out.parent / ".filled-sample.pdf"
    with open(tmp, "wb") as fh:
        writer.write(fh)

    read = json.loads(subprocess.run(
        [sys.executable, str(HERE / "read_transfer_sheet.py"), str(tmp)],
        capture_output=True, text=True, check=True,
    ).stdout)
    tmp.unlink()

    out.write_text(json.dumps({
        "_comment": (
            "Captured from a real PDF: generated by tools/transfer_sheet.py, filled, and read back by "
            "tools/read_transfer_sheet.py. Regenerate with tools/make-fixture.py whenever the sheet "
            "changes. These are raw AcroForm values, exactly as they come off the file."
        ),
        "sheet_version": SAMPLE["sheet_version"],
        "pages": read["pages"],
        "field_count": read["field_count"],
        "field_names": field_names,
        "values": read["values"],
    }, indent=2) + "\n")

    print(f"wrote {out} — {read['field_count']} fields, {len(read['values'])} values")


if __name__ == "__main__":
    main(ROOT / "out" / "RaiseRoom_Transfer-Sheet.pdf", ROOT / "test" / "transfer-sheet-fixture.json")
