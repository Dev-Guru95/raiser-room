/**
 * Export the Transfer Sheet field definitions as JSON, for the Python PDF
 * generator to consume.
 *
 * The generator is in Python (reportlab writes AcroForms; there is no
 * zero-dependency Node equivalent) and the definitions are in JavaScript
 * (the app imports them). Rather than keep two copies of the field table — the
 * exact drift this module exists to prevent — the JavaScript is the source and
 * this script emits what Python reads.
 *
 *   node tools/dump-fields.mjs > tools/fields.json
 */

import {
  TRANSFER_SHEET_VERSION, META_FIELDS, SCORE_FIELDS, FACT_FIELDS,
  KEY_PERSON_FIELDS, ALL_FIELD_NAMES, DIRECTION_CHOICES,
} from '../src/domain/transfer-sheet.js';
import { DOMAINS, SCALE } from '../src/domain/criteria.js';

const payload = {
  _comment: 'GENERATED by tools/dump-fields.mjs from src/domain/transfer-sheet.js. Do not edit by hand.',
  version: TRANSFER_SHEET_VERSION,
  meta: META_FIELDS,
  direction_choices: DIRECTION_CHOICES,
  scale: SCALE,
  domains: DOMAINS.map((d) => ({
    n: d.n, name: d.name, weight: d.weight, question: d.question,
    criteria: d.criteria.map((c) => ({
      ref: c.ref, text: c.text,
      field: SCORE_FIELDS.find((f) => f.ref === c.ref).field,
    })),
  })),
  fact_fields: FACT_FIELDS,
  key_person_fields: KEY_PERSON_FIELDS,
  all_field_names: ALL_FIELD_NAMES,
};

process.stdout.write(`${JSON.stringify(payload, null, 2)}\n`);
